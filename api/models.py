from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional, Literal

# --- Request Models (Data coming IN to the API) ---

class QueryRequest(BaseModel):
    question: str = Field(
        ..., 
        description="The question you want to ask the RAG pipeline."
    )
    retrieval_mode: Literal["hybrid", "dense"] = Field(
        default="hybrid",
        description="Retrieval mode: 'hybrid' (dense+BM25+RRF+rerank) or 'dense' (vector-only)."
    )

class IngestRequest(BaseModel):
    text: str = Field(
        ..., 
        description="The raw text content to be chunked and embedded."
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Source metadata (e.g., {'title': 'Architecture Doc', 'author': 'Huddl'})"
    )

# --- Response Models (Data going OUT of the API) ---

class Citation(BaseModel):
    text: str = Field(description="The actual text of the retrieved chunk.")
    metadata: Dict[str, Any] = Field(description="Metadata attached to this chunk.")
    score: Optional[float] = Field(default=None, description="Vector similarity distance score.")
    index: Optional[int] = Field(
        default=None,
        description="1-based citation number used in the answer (e.g. [2] maps to index 2)."
    )

class RetrievedChunk(BaseModel):
    rank: int = Field(description="1-based rank in the retrieved result list.")
    chunk_id: Optional[str] = Field(default=None, description="Unique chunk identifier.")
    source_file: Optional[str] = Field(default=None, description="Source document file.")
    text: str = Field(description="The chunk text.")
    display_score: float = Field(description="Normalized score for display.")
    is_percentage: bool = Field(
        description="True if display_score is a 0-1 percentage (hybrid); False if it is a raw distance (dense)."
    )

class DocumentChunk(BaseModel):
    chunk_id: str
    chunk_index: int
    text: str

class DocumentFile(BaseModel):
    source_file: str
    total_chunks: int
    chunks: List[DocumentChunk]

class JudgeResponse(BaseModel):
    citation_analysis: str = Field(
        description="Chain-of-Thought reasoning that lists existing context indices and verifies each bracketed citation for in-bounds validity and support."
    )
    atomic_claims: List[str] = Field(
        description="Discrete factual claims extracted from the generated answer."
    )
    total_claims: int = Field(
        description="Number of atomic claims (must equal len(atomic_claims))."
    )
    supported_claims: int = Field(
        description="Number of claims backed by an in-bounds retrieved context block."
    )
    answer_relevance_score: int = Field(
        description="Answer relevance on a 0-10 integer scale."
    )
    unsupported_citations: List[str] = Field(
        default_factory=list,
        description="Bracketed citations that are out-of-bounds or unsupported by the retrieved context."
    )

class QueryResponse(BaseModel):
    answer: str = Field(description="The final answer generated by the LLM.")
    model: Optional[str] = Field(default=None, description="Generator model that produced the answer.")
    citations: List[Citation] = Field(description="List of chunks retrieved from ChromaDB.")
    all_retrieved_chunks: List[RetrievedChunk] = Field(
        default_factory=list,
        description="All retrieved chunks ranked by relevance, with normalized display scores."
    )
    confidence_scores: Dict[str, float] = Field(
        default_factory=dict,
        description="Optional metric breakdown (e.g., {'retrieval_relevance': 0.95})"
    )
    raw_judge_response: Optional[JudgeResponse] = Field(
        default=None,
        description="Structured judge output including citation_analysis, atomic_claims, total_claims, supported_claims, answer_relevance_score, unsupported_citations."
    )