from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional, Literal

# --- Request Models (Data coming IN to the API) ---

class QueryRequest(BaseModel):
    question: str = Field(
        ..., 
        description="The question you want to ask the RAG pipeline."
    )
    retrieval_mode: Literal["hybrid", "dense"] = Field(
        default="hybrid",
        description="Retrieval mode: 'hybrid' (dense+BM25+RRF+rerank) or 'dense' (vector-only)."
    )

class IngestRequest(BaseModel):
    text: str = Field(
        ..., 
        description="The raw text content to be chunked and embedded."
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Source metadata (e.g., {'title': 'Architecture Doc', 'author': 'Huddl'})"
    )

# --- Response Models (Data going OUT of the API) ---

class Citation(BaseModel):
    text: str = Field(description="The actual text of the retrieved chunk.")
    metadata: Dict[str, Any] = Field(description="Metadata attached to this chunk.")
    score: Optional[float] = Field(default=None, description="Vector similarity distance score.")

class QueryResponse(BaseModel):
    answer: str = Field(description="The final answer generated by the LLM.")
    citations: List[Citation] = Field(description="List of chunks retrieved from ChromaDB.")
    confidence_scores: Dict[str, float] = Field(
        default_factory=dict,
        description="Optional metric breakdown (e.g., {'retrieval_relevance': 0.95})"
    )